"""Generate src/drawlist_sites.inl for NFS13Unlimiter.asi from NFS13_dump.exe.

Every call to DispatchList::PreAllocateContiguousKeyBlock (0xa69bb0) reserves a fixed number of draw keys for one
list; one item past that and the renderer reads an empty entry. Each `push imm32` size before such a call becomes a
site: the ui lists (UIEntityModule::GenerateDispatchLists) get UI_KEYS, the rest double. Sizes pushed as imm8 or from
a register are left alone.

usage: python gen_drawlists.py"""
import os
import struct

from capstone import Cs, CS_ARCH_X86, CS_MODE_32

EXE = r'F:/SteamLibrary/steamapps/common/Need for Speed(TM) Most Wanted/NFS13_dump.exe'
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'src', 'drawlist_sites.inl')
BASE, TARGET = 0x400000, 0xa69bb0
UI = range(0x624940, 0x624a80)
UI_KEYS = 0x800
EXPECT = 36


def main():
    d = open(EXE, 'rb').read()
    md = Cs(CS_ARCH_X86, CS_MODE_32)
    rows = []
    for o in range(0x1000, 0xc00000):
        if d[o] != 0xe8 or (BASE + o + 5 + struct.unpack_from('<i', d, o + 1)[0]) & 0xffffffff != TARGET:
            continue
        call = BASE + o
        # the size argument is the last push before the call; only `add/sub ecx` may sit between them
        ins = [i for i in md.disasm(d[o - 24:o], call - 24)]
        push = next((i for i in reversed(ins) if i.mnemonic == 'push'), None)
        if push is None or push.bytes[0] != 0x68:
            continue
        between = d[push.address - BASE:o]
        old = struct.unpack_from('<I', d, push.address - BASE + 1)[0]
        if old < 0x80:
            continue
        new = UI_KEYS if call in UI and old == 0x200 else old * 2
        rows.append((push.address, between, old, new))
    assert len(rows) == EXPECT, f'{len(rows)} sites, expected {EXPECT}: the exe is not the one analysed'
    lines = ['// generated by tools/gen_drawlists.py: draw list sizes (push size; add/sub ecx, list)',
             'const Raise kDrawListSites[] = {']
    for a, b, old, new in rows:
        lines.append(f'    {{{{0x{a:x}, {len(b)}, 1, {{{", ".join(f"0x{x:02x}" for x in b)}}}}}, 0x{new:x}}},'
                     f'  // 0x{old:x} -> 0x{new:x}')
    lines.append('};')
    open(OUT, 'w').write('\n'.join(lines) + '\n')
    print(f'{len(rows)} sites -> {OUT}')


if __name__ == '__main__':
    main()
