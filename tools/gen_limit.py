"""Generate src/jackspot_sites.inl for NFS13Unlimiter.asi from NFS13_dump.exe.

The CarSwapLogic HSM behaviour (0x74d0 bytes, CreateNew at 0x77f790) embeds ArrayList<RaceCarSwapSpotData, 185> at
+0x50 (stride 0xa0, count at array+0x73a0 = object+0x73f0); everything after the array (count and ~0xe0 bytes of
fields) moves out by DELTA so the array holds CAPACITY spots. Every instruction carrying an offset into that tail
uses a 4-byte displacement or immediate, so each is a same-size patch.

Sites: every 4-byte constant in [0x73a0, 0x74d0) inside the class's code (0x73a000-0x770000), decoded from real
function starts, minus 0x764d90 (another class: its object has fields at 0x3ff0/0x59f0, and nothing calls it); the
ambiguous 0x73a0..0x73ef ones are all the count reached through the array base. Plus the two 0x74d0 size constants.

usage: python gen_limit.py [capacity]"""
import bisect
import os
import re
import struct
import sys

from capstone import Cs, CS_ARCH_X86, CS_MODE_32
from capstone.x86 import X86_OP_IMM, X86_OP_MEM

EXE = r'F:/SteamLibrary/steamapps/common/Need for Speed(TM) Most Wanted/NFS13_dump.exe'
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(HERE), 'src', 'jackspot_sites.inl')
BASE, STRIDE, OLD_CAP = 0x400000, 0xa0, 185
LO, HI, ARRAY = 0x73a000, 0x770000, 0x50
TAIL_ARRAY_REL, TAIL_OBJ, SIZE = 0x73a0, 0x73f0, 0x74d0
NOT_OURS = {0x764d90}
SIZE_SITES = {0x77f79c: 'CreateNew allocation', 0x758c32: 'debug type registration'}   # push 0x74d0
EXPECT_SITES = 224 - len(NOT_OURS)


def main(cap):
    assert OLD_CAP < cap < 256, 'spot indices must stay below 0xff'
    delta = (cap - OLD_CAP) * STRIDE
    assert delta % 16 == 0
    d = open(EXE, 'rb').read()
    pe = struct.unpack_from('<I', d, 0x3c)[0]
    opt = struct.unpack_from('<H', d, pe + 20)[0]
    secs = []
    for i in range(struct.unpack_from('<H', d, pe + 6)[0]):
        o = pe + 24 + opt + 40 * i
        secs.append((d[o:o + 8].rstrip(b'\0'), *struct.unpack_from('<IIII', d, o + 8)))
    name, vsize, va, rsize, raw = next(s for s in secs if s[0] == b'.text')
    code = d[raw:raw + rsize]
    off = lambda a: a - BASE - va + raw
    md = Cs(CS_ARCH_X86, CS_MODE_32)
    md.detail = True
    # two independent decodes must agree on every site's instruction: from real function starts (call targets and
    # pointers in the data sections), and by majority over 40 linear decodes from earlier byte offsets (x86 resyncs)
    starts = set()
    for m in re.finditer(rb'\xe8', code):
        k = m.start()
        if k + 5 <= len(code):
            t = BASE + va + k + 5 + struct.unpack_from('<i', code, k + 1)[0]
            if BASE + va <= t < BASE + va + rsize:
                starts.add(t)
    for nm, vs, v, rs, r0 in secs:
        if nm in (b'.rdata', b'.data'):
            blob = d[r0:r0 + rs]
            for k in range(0, len(blob) - 3, 4):
                q = struct.unpack_from('<I', blob, k)[0]
                if BASE + va <= q < BASE + va + rsize:
                    starts.add(q)
    starts = sorted(starts)

    def by_start(p):
        f = starts[bisect.bisect_right(starts, p) - 1]
        return next((i for i in md.disasm(d[off(f):off(p) + 16], f) if i.address <= p and p + 4 <= i.address + i.size), None)

    def by_sync(p):
        votes = {}
        for back in range(41, 81):
            i = next((i for i in md.disasm(d[off(p - back):off(p) + 16], p - back) if i.address <= p < i.address + i.size), None)
            if i is not None and p + 4 <= i.address + i.size:
                votes[i.address] = votes.get(i.address, 0) + 1
        best = max(votes, key=votes.get) if votes else None
        return next(md.disasm(d[off(best):off(best) + 16], best), None) if best and votes[best] >= 30 else None

    sites = []
    for m in re.finditer(rb'[\x00-\xff][\x73\x74]\x00\x00', d[off(LO):off(HI)]):
        p = LO + m.start()
        v = struct.unpack_from('<I', d, off(p))[0]
        if not TAIL_ARRAY_REL <= v < SIZE:
            continue
        ins, alt = by_start(p), by_sync(p)
        assert alt is None or (ins and ins.address) == alt.address, f'{p:#x}: decodes disagree'   # None: no majority
        if ins is None or ins.address in NOT_OURS:
            continue
        if not any((op.type == X86_OP_MEM and op.mem.disp == v) or (op.type == X86_OP_IMM and op.imm == v) for op in ins.operands):
            continue
        sites.append((ins.address, bytes(ins.bytes), p - ins.address, v, f'{ins.mnemonic} {ins.op_str}'))
    assert len(sites) == EXPECT_SITES, f'{len(sites)} sites, expected {EXPECT_SITES}: the exe is not the one analysed'
    for a, what in SIZE_SITES.items():
        b = d[off(a):off(a) + 5]
        assert b == b'\x68' + struct.pack('<I', SIZE), (hex(a), b.hex())
        sites.append((a, b, 1, SIZE, f'push 0x{SIZE:x} ; {what}'))
    lines = [f'// generated by tools/gen_limit.py: capacity {cap}, tail moved by 0x{delta:x}',
             f'constexpr int kCapacity = {cap};', f'constexpr uint32_t kDelta = 0x{delta:x};', 'const Site kSites[] = {']
    for a, b, fo, v, txt in sorted(sites):
        lines.append(f'    {{0x{a:x}, {len(b)}, {fo}, {{{", ".join(f"0x{x:02x}" for x in b)}}}}},  // {txt}')
    lines.append('};')
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, 'w').write('\n'.join(lines) + '\n')
    print(f'{len(sites)} sites, capacity {cap}, delta 0x{delta:x}, object 0x{SIZE:x} -> 0x{SIZE + delta:x} -> {OUT}')


if __name__ == '__main__':
    main(int(sys.argv[1]) if len(sys.argv) > 1 else 240)
